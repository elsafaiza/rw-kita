let bahasaAktif = localStorage.getItem("rwKitaLanguage") || "id";
let sedangMenerjemahkan = false;
let timerTerjemahan;

function normalisasi(teks) { return String(teks || "").replace(/\s+/g, " ").trim(); }

function cariTerjemahan(teks) {
  const normal = normalisasi(teks);
  for (const id in translations) {
    const en = translations[id];
    if (id === normal || en === normal) return { id, en };
  }
  return null;
}

function teksDinamis(teks, bahasa) {
  const normal = normalisasi(teks);
  const rw = normal.match(/RW\s*\d+/i)?.[0];
  if (!rw) return null;
  if (bahasa === "en") {
    if (/^Hubungi RW/i.test(normal)) return `Contact ${rw}`;
    if (/^Informasi RW/i.test(normal)) return `Information ${rw}`;
    if (/^Potensi RW/i.test(normal)) return `${rw} Potential`;
    if (/^Produk Hukum RW/i.test(normal)) return `Legal Products ${rw}`;
    if (/^Arsip Digital RW/i.test(normal)) return `Digital Archive ${rw}`;
    if (/^Statistik RW/i.test(normal)) return `${rw} Statistics`;
    if (/^Ketua RW/i.test(normal)) return `Chairperson ${rw}`;
  } else {
    if (/^Contact RW/i.test(normal)) return `Hubungi ${rw}`;
    if (/^Information RW/i.test(normal)) return `Informasi ${rw}`;
    if (/^RW.*Potential/i.test(normal)) return `Potensi ${rw}`;
    if (/^Legal Products RW/i.test(normal)) return `Produk Hukum ${rw}`;
    if (/^Digital Archive RW/i.test(normal)) return `Arsip Digital ${rw}`;
    if (/^RW.*Statistics/i.test(normal)) return `Statistik ${rw}`;
    if (/^Chairperson RW/i.test(normal)) return `Ketua ${rw}`;
  }
  return null;
}

function denganSpasi(lama, baru) {
  const awal = String(lama).match(/^\s*/)?.[0] || "";
  const akhir = String(lama).match(/\s*$/)?.[0] || "";
  return awal + baru + akhir;
}

function terjemahkanDataI18n(bahasa) {
  document.querySelectorAll("[data-i18n]").forEach(element => {
    const id = element.dataset.i18n;
    if (!translations[id]) return;
    const hasil = bahasa === "en" ? translations[id] : id;
    if (element.textContent.trim() !== hasil) element.textContent = hasil;
  });
}

function terjemahkanTeksBiasa(bahasa) {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const nodes = [];
  let node;
  while ((node = walker.nextNode())) nodes.push(node);

  nodes.forEach(textNode => {
    const parent = textNode.parentElement;
    if (!parent || parent.closest("script, style, noscript, textarea, .language-switch, .language-menu")) return;
    const lama = textNode.textContent;
    const normal = normalisasi(lama);
    if (!normal) return;

    const dinamis = teksDinamis(normal, bahasa);
    const terjemahan = cariTerjemahan(normal);
    const hasil = dinamis || (terjemahan ? bahasa === "en" ? terjemahan.en : terjemahan.id : null);
    if (hasil && hasil !== normal) textNode.textContent = denganSpasi(lama, hasil);
  });
}

function terjemahkanPlaceholder(bahasa) {
  document.querySelectorAll("[placeholder]").forEach(input => {
    const sumber = input.dataset.i18nPlaceholder || input.placeholder;
    const terjemahan = cariTerjemahan(sumber);
    if (!terjemahan) return;
    input.dataset.i18nPlaceholder = terjemahan.id;
    input.placeholder = bahasa === "en" ? terjemahan.en : terjemahan.id;
  });
}

function terjemahkanAtribut(bahasa) {
  document.querySelectorAll("[title], img[alt]").forEach(element => {
    const atribut = element.hasAttribute("title") ? "title" : "alt";
    const sumber = element.getAttribute(atribut);
    const terjemahan = cariTerjemahan(sumber);
    if (terjemahan) element.setAttribute(atribut, bahasa === "en" ? terjemahan.en : terjemahan.id);
  });
}

function perbaruiToggle(bahasa) {
  const toggle = document.getElementById("languageToggle");
  if (toggle) toggle.checked = bahasa === "en";
}

function terapkanBahasa(bahasa) {
  bahasaAktif = bahasa === "en" ? "en" : "id";
  localStorage.setItem("rwKitaLanguage", bahasaAktif);
  sedangMenerjemahkan = true;
  terjemahkanDataI18n(bahasaAktif);
  terjemahkanTeksBiasa(bahasaAktif);
  terjemahkanPlaceholder(bahasaAktif);
  terjemahkanAtribut(bahasaAktif);
  perbaruiToggle(bahasaAktif);
  document.documentElement.lang = bahasaAktif;
  requestAnimationFrame(() => {
    document.documentElement.classList.remove("language-loading");
    sedangMenerjemahkan = false;
  });
}

function changeLanguage(bahasa) { terapkanBahasa(bahasa); }

document.addEventListener("DOMContentLoaded", () => {
  const toggle = document.getElementById("languageToggle");
  if (toggle) {
    toggle.checked = bahasaAktif === "en";
    toggle.addEventListener("change", () => terapkanBahasa(toggle.checked ? "en" : "id"));
  }

  terapkanBahasa(bahasaAktif);

  const observer = new MutationObserver(() => {
    if (sedangMenerjemahkan) return;
    clearTimeout(timerTerjemahan);
    timerTerjemahan = setTimeout(() => terapkanBahasa(bahasaAktif), 50);
  });

  observer.observe(document.body, { childList: true, subtree: true });
});

window.terapkanBahasa = terapkanBahasa;
window.changeLanguage = changeLanguage;
